const { contextBridge, ipcRenderer } = require('electron');
const inv = (c, ...a) => ipcRenderer.invoke(c, ...a);
contextBridge.exposeInMainWorld('api', {
  cfg: { get: () => inv('cfg:get'), set: p => inv('cfg:set', p) },
  latest: () => inv('latest'), launch: u => inv('launch', u),
  openMods: () => inv('mods:open'), reset: () => inv('reset'),
  pickSlot: id => inv('slot:pick', id), clearSlot: id => inv('slot:clear', id),
  pickIcon: () => inv('icon:pick'), clearIcon: () => inv('icon:clear'), getIcon: () => inv('icon:get'),
  pickBg: () => inv('bg:pick'), clearBg: () => inv('bg:clear'), getBg: () => inv('bg:get'),
  pickExe: () => inv('exe:pick'),
  findServers: q => inv('servers:find', q), history: () => inv('history:get'), clearHistory: () => inv('history:clear'),
  cleanCache: () => inv('cache:clean'), packs: () => inv('packs:list'), openPacks: () => inv('packs:open'),
  importPack: () => inv('packs:import'), deletePack: n => inv('packs:delete', n),
  addAccount: () => inv('acc:add'), removeAccount: id => inv('acc:remove', id),
  libGet: () => inv('lib:get'), libFav: (id, v) => inv('lib:fav', id, v), libRemove: id => inv('lib:remove', id), libAdd: q => inv('lib:add', q),
  libSet: (id, p) => inv('lib:set', id, p), discover: f => inv('discover:search', f),
  newsGet: () => inv('news:get'), newsCheck: () => inv('news:check'), newsSeen: () => inv('news:seen'),
  stats: () => inv('stats:get'), friends: () => inv('friends:get'),
  studioFind: () => inv('studio:find'), studioLaunch: f => inv('studio:launch', f), studioPath: () => inv('studio:path'), studioDownload: () => inv('studio:download'),
  integrity: m => inv('integrity:run', m), overlayPreview: () => inv('overlay:preview'),
  pickBgVideo: () => inv('bgv:pick'), clearBgVideo: () => inv('bgv:clear'), getBgVideo: () => inv('bgv:get'),
  updateGet: () => inv('update:get'), updateCheck: () => inv('update:check'), updateDownload: () => inv('update:download'), updateInstall: () => inv('update:install'),
  onUpdate: cb => ipcRenderer.on('update:status', (_, s) => cb(s)),
  onNews: cb => ipcRenderer.on('news:badge', (_, n) => cb(n)), onItg: cb => ipcRenderer.on('itg', (_, d) => cb(d)),
  links: () => inv('links:get'), setLink: (id, on) => inv('links:set', id, on),
  applyCss: css => inv('css:apply', css),
  win: a => ipcRenderer.send('win', a), winLook: o => ipcRenderer.send('win:look', o),
  onProgress: cb => ipcRenderer.on('progress', (_, d) => cb(d)),
  onBoot: cb => ipcRenderer.on('boot', (_, d) => cb(d)),
  onActivity: cb => ipcRenderer.on('activity', (_, d) => cb(d)),
});
